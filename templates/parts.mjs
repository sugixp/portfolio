// Small building blocks shared by the page templates.
import { existsSync } from "node:fs";
import { join } from "node:path";
import { html } from "../scripts/lib/html.mjs";
import { localize } from "../scripts/lib/localize.mjs";

/** "2027" stays as is; "2027-12" becomes "dez/2027" or "Dec 2027", per the page language. */
function formatYearMonth(t, value) {
    const [year, month] = value.split("-");
    if (!month) return year;
    const name = new Intl.DateTimeFormat(t("_meta.htmlLang"), { month: "short", timeZone: "UTC" })
        .format(new Date(Date.UTC(Number(year), Number(month) - 1, 1)))
        .replace(/\.$/, ""); // pt-BR abbreviates as "dez."
    return t("experience.monthYear", { month: name, year });
}

/** "2023–2025", "2025–atual" or, with expectedEnd, "2025 – previsão de conclusão dez/2027". */
export function dateRange(t, item) {
    if (item.end) return `${item.start}–${item.end}`;
    if (item.expectedEnd) return `${item.start} – ${t("experience.expected", { date: formatYearMonth(t, item.expectedEnd) })}`;
    return `${item.start}–${t("experience.present")}`;
}

const STATUS_LAMP = { deployed: "ok", stable: "ok", "in-progress": "warn", archived: "off" };

/**
 * A signal lamp. Colour is never the only cue: the lamp always comes with its
 * state written next to it, and the lamp itself is hidden from screen readers.
 */
export function lamp(kind, text) {
    return html`<span class="lamp-state lamp-state-${kind}"><span class="lamp lamp-${kind}" aria-hidden="true"></span>${text}</span>`;
}

export function statusLamp(status, label) {
    return lamp(STATUS_LAMP[status] ?? "off", label);
}

// Responsive widths generated by scripts/project-previews.mjs.
export const PREVIEW_WIDTHS = [640, 1280];

function imagePreview(ctx, project) {
    const name = `assets/projects/${project.id}`;
    const files = PREVIEW_WIDTHS.flatMap((w) => ["avif", "webp"].map((ext) => `${name}-${w}.${ext}`));
    // A missing image only drops the preview; the card itself still renders.
    if (!files.every((f) => existsSync(join(ctx.root, f)))) return null;
    const srcset = (ext) => PREVIEW_WIDTHS.map((w) => `${ctx.base}${name}-${w}.${ext} ${w}w`).join(", ");
    const sizes = project.featured ? "(max-width: 900px) 100vw, 600px" : "(max-width: 900px) 100vw, 340px";
    return html`<picture>
                  <source type="image/avif" srcset="${srcset("avif")}" sizes="${sizes}" />
                  <source type="image/webp" srcset="${srcset("webp")}" sizes="${sizes}" />
                  <img src="${ctx.base}${name}-640.webp" alt="${localize(project.preview.alt, ctx.lang)}" width="1280" height="800" loading="lazy" decoding="async" />
                </picture>`;
}

// Command-line projects: the run example from the repository README, rendered
// as text (selectable, translatable by the browser, zero image bytes).
function terminalPreview(ctx, project) {
    const { command, output } = project.preview;
    return html`<figure class="term">
                  <pre><code><span class="term-prompt">$ ${command}</span>
${output.join("\n")}</code></pre>
                  <figcaption class="visually-hidden">${ctx.t("projects.terminalCaption")} ${command}</figcaption>
                </figure>`;
}

export function projectPreview(ctx, project) {
    if (!project.preview) return null;
    if (project.preview.type === "terminal") return terminalPreview(ctx, project);
    if (project.preview.type === "screenshot") return imagePreview(ctx, project);
    return null;
}
